#Requires -Version 5.1
<#
.SYNOPSIS
    Drive mock-sut fault modes through mytool run and summarise classifier output (P0-55).
.PARAMETER OutFile
    Write markdown report (default docs/reviews/classifier-coverage.md).
#>
[CmdletBinding()]
param(
    [string]$OutFile = ''
)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/lib/aitest-run.ps1"

$repo = Get-RepoRoot
if (-not $OutFile) {
    $OutFile = Join-Path $repo 'docs/reviews/classifier-coverage.md'
}

Invoke-RepoCargo -Args @('build', '-q', '-p', 'mock-sut', '-p', 'cli') -RepoRoot $repo

$serial = Join-Path $repo 'examples/serial.yaml'
$scenarios = @(
    @{
        Name      = 'http_500'
        Dag       = $serial
        MockArgs  = @('--fault-internal-error')
        ExpectExit = 1
    },
    @{
        Name      = 'corrupt_create_field'
        Dag       = $serial
        MockArgs  = @('--fault-corrupt-create-field')
        ExpectExit = 1
    },
    @{
        Name      = 'assertion_mismatch'
        Dag       = $serial
        MockArgs  = @()
        ExtraRun  = @('--parallel', '1')
        PatchYaml = $true
    },
    @{
        Name      = 'connection_refused'
        Dag       = $serial
        BaseUrl   = 'http://127.0.0.1:1'
        ExpectExit = 1
    }
)

$rows = New-Object System.Collections.Generic.List[object]

foreach ($scenario in $scenarios) {
    $sut = $null
  $workspace = $null
    try {
        if ($scenario.BaseUrl) {
            $workspace = New-RunWorkspace -BaseUrl $scenario.BaseUrl
        }
        else {
            $sut = Start-MockSut -RepoRoot $repo -ExtraArgs $scenario.MockArgs
            $workspace = New-RunWorkspace -BaseUrl $sut.BaseUrl
        }

        $dag = $scenario.Dag
        if ($scenario.PatchYaml) {
            $raw = Get-Content $dag -Raw
            $raw = $raw.Replace('expected: 200', 'expected: 201')
            $patched = Join-Path $workspace 'serial-bad.yaml'
            Set-Content -Path $patched -Value $raw -Encoding utf8
            $dag = $patched
        }

        $reportPath = Join-Path $workspace 'report.json'
        $extra = @('--report-json', $reportPath)
        if ($scenario.ExtraRun) {
            $extra += $scenario.ExtraRun
        }
        $result = Invoke-MytoolRun -RepoRoot $repo -Workspace $workspace -DagPath $dag -ExtraArgs $extra

        $category = ''
        $code = ''
        $node = ''
        if (Test-Path $reportPath) {
            $report = Get-Content $reportPath -Raw | ConvertFrom-Json
            foreach ($prop in $report.deterministic.nodes.PSObject.Properties) {
                $n = $prop.Value
                if ($n.status -eq 'FAILED' -and $n.failure) {
                    $node = $prop.Name
                    $category = $n.failure.category
                    $code = $n.failure.error_code
                    break
                }
            }
        }
        if (-not $category) { $category = 'unknown' }
        if (-not $code) { $code = 'UNKNOWN' }

        $rows.Add([PSCustomObject]@{
                Scenario = $scenario.Name
                ExitCode = $result.ExitCode
                Node     = $node
                Category = $category
                Code     = $code
            })
    }
    finally {
        Stop-MockSut $sut
    }
}

$total = $rows.Count
$unknown = @($rows | Where-Object { $_.Category -eq 'unknown' -or $_.Code -eq 'UNKNOWN' }).Count
$pct = if ($total) { [math]::Round(100.0 * $unknown / $total, 1) } else { 0 }

$lines = @(
    '# Classifier coverage (mock-sut fault injection)',
    ''
    "Generated by ``scripts/classifier-coverage.ps1``. Samples: **$total**, unknown: **$unknown** (**$pct%**)."
    ''
    '| Scenario | Exit | Node | Category | error_code |'
    '|---|---:|---|---|---|'
)

foreach ($r in $rows) {
    $lines += "| $($r.Scenario) | $($r.ExitCode) | $($r.Node) | $($r.Category) | $($r.Code) |"
}

$gaps = @($rows | Where-Object { $_.Category -eq 'unknown' } | ForEach-Object { $_.Scenario })
if ($gaps.Count) {
    $lines += ''
    $lines += '## Rules to add'
    foreach ($g in $gaps) {
        $lines += "- $g"
    }
}
else {
    $lines += ''
    $lines += 'No `unknown` classifications in this drill (extend scenarios if new fault modes are added).'
}

$text = $lines -join "`n"
Write-Host $text

$dir = Split-Path $OutFile -Parent
if (-not (Test-Path $dir)) {
    New-Item -ItemType Directory -Path $dir -Force | Out-Null
}
Set-Content -Path $OutFile -Value $text -Encoding utf8

if ($unknown -gt 0) {
    Write-Warning "$unknown/$total samples were unknown — see $OutFile"
}
exit 0
